const run = async () => {
  await connectDB();

  try {
    const deletedDaybook = await DayBook.deleteMany({
      shop: SHOP_ID,
      date: { $gte: RANGE_START, $lt: RANGE_END },
    });
    console.log(
      `Deleted ${deletedDaybook.deletedCount} existing daybook entries for Pushpanjali Hospital`,
    );

    // Remove duplicate dates before inserting.
    // The source contains zero-value placeholder records for:
    // 2026-03-01
    // 2026-03-02
    // 2026-03-03
    // 2026-05-01
    //
    // Keep the LAST occurrence because it contains the actual
    // financial data.

    const uniqueEntries = Array.from(
      new Map(rawEntries.map((entry) => [entry.date, entry])).values(),
    );

    console.log(`Source entries: ${rawEntries.length}`);

    console.log(`Unique entries: ${uniqueEntries.length}`);

    const docs = uniqueEntries.map(buildEntry);

    const result = await DayBook.insertMany(docs, {
      ordered: true,
    });

    console.log(
      `Inserted ${result.length} daybook entries for Pushpanjali Hospital`,
    );
    console.log(
      `Inserted ${result.length} daybook entries for Pushpanjali Hospital`,
    );

    // Ensure partners exist, then reseed their transactions for this shop + range
    const partnerNames = Object.keys(partnerTxnsByName);
    const partnerMap = {};
    for (const name of partnerNames) {
      let partner = await Partner.findOne({ name });
      if (!partner) partner = await Partner.create({ name });
      partnerMap[name] = partner._id;
    }

    const deletedTxns = await PartnerTransaction.deleteMany({
      shop: SHOP_ID,
      partner: { $in: Object.values(partnerMap) },
      date: { $gte: RANGE_START, $lt: RANGE_END },
    });
    console.log(
      `Deleted ${deletedTxns.deletedCount} existing partner transactions for this shop/range`,
    );

    const txnDocs = [];
    for (const [name, txns] of Object.entries(partnerTxnsByName)) {
      txns.forEach((t) =>
        txnDocs.push({ ...t, partner: partnerMap[name], shop: SHOP_ID }),
      );
    }
    if (txnDocs.length) {
      const txnResult = await PartnerTransaction.insertMany(txnDocs, {
        ordered: true,
      });
      console.log(
        `Inserted ${txnResult.length} partner transactions for Pushpanjali Hospital`,
      );
    } else {
      console.log(
        "No partner transactions found in source data for Pushpanjali Hospital",
      );
    }

    const first = result[0];
    const last = result[result.length - 1];
    console.log(
      `Opening cash on ${first.date.toDateString()}: Rs ${first.openingCash}`,
    );
    console.log(
      `Closing cash on ${last.date.toDateString()}: Rs ${last.cashInHand}`,
    );
  } catch (err) {
    console.error("Seed failed:", err.message);
  } finally {
    await mongoose.connection.close();
    process.exit(0);
  }
};

run();
